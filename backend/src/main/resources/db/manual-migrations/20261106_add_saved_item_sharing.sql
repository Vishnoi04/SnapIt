-- Requires the user and saved-item ownership schema to be applied first.
CREATE TABLE saved_item_shares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    saved_item_id BIGINT NOT NULL,
    recipient_user_id BIGINT NOT NULL,
    shared_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_saved_item_share_recipient UNIQUE (saved_item_id, recipient_user_id),
    CONSTRAINT fk_saved_item_shares_item FOREIGN KEY (saved_item_id)
        REFERENCES saved_items (id) ON DELETE CASCADE,
    CONSTRAINT fk_saved_item_shares_recipient FOREIGN KEY (recipient_user_id)
        REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_saved_item_shares_recipient
    ON saved_item_shares (recipient_user_id);
