-- Requires the saved-item ownership schema to be applied first.
CREATE TABLE reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    saved_item_id BIGINT NOT NULL,
    message VARCHAR(500),
    remind_at TIMESTAMP NOT NULL,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_reminders_saved_item FOREIGN KEY (saved_item_id)
        REFERENCES saved_items (id) ON DELETE CASCADE
);

CREATE INDEX idx_reminders_saved_item_remind_at
    ON reminders (saved_item_id, remind_at);
