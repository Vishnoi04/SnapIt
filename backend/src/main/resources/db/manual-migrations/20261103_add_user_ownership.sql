-- Legacy saved items have no recoverable owner; keep them unowned and inaccessible
-- until an explicit account-to-item ownership mapping is approved.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

ALTER TABLE saved_items
    ADD COLUMN user_id BIGINT;

ALTER TABLE saved_items
    ALTER COLUMN extracted_text TYPE TEXT
    USING extracted_text::TEXT;

ALTER TABLE saved_items
    ADD CONSTRAINT fk_saved_items_user
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE;

CREATE INDEX idx_saved_items_user_id ON saved_items (user_id);
