-- Requires the ownership-schema migration and the saved-item favorites migration first.
CREATE TABLE collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(1000),
    created_at TIMESTAMP NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT uk_collections_user_name UNIQUE (user_id, name),
    CONSTRAINT fk_collections_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_collections_user_id ON collections (user_id);

CREATE TABLE collection_saved_items (
    collection_id BIGINT NOT NULL,
    saved_item_id BIGINT NOT NULL,
    CONSTRAINT pk_collection_saved_items PRIMARY KEY (collection_id, saved_item_id),
    CONSTRAINT fk_collection_saved_items_collection FOREIGN KEY (collection_id)
        REFERENCES collections (id) ON DELETE CASCADE,
    CONSTRAINT fk_collection_saved_items_item FOREIGN KEY (saved_item_id)
        REFERENCES saved_items (id) ON DELETE CASCADE
);

CREATE INDEX idx_collection_saved_items_item_id ON collection_saved_items (saved_item_id);

CREATE TABLE tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT uk_tags_user_name UNIQUE (user_id, name),
    CONSTRAINT fk_tags_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_tags_user_id ON tags (user_id);

CREATE TABLE saved_item_tags (
    tag_id BIGINT NOT NULL,
    saved_item_id BIGINT NOT NULL,
    CONSTRAINT pk_saved_item_tags PRIMARY KEY (tag_id, saved_item_id),
    CONSTRAINT fk_saved_item_tags_tag FOREIGN KEY (tag_id)
        REFERENCES tags (id) ON DELETE CASCADE,
    CONSTRAINT fk_saved_item_tags_item FOREIGN KEY (saved_item_id)
        REFERENCES saved_items (id) ON DELETE CASCADE
);

CREATE INDEX idx_saved_item_tags_item_id ON saved_item_tags (saved_item_id);
